import { Bell, BellRing, CheckCheck, Info, Radar, Sparkles, Trash2 } from 'lucide-react';
import { Link } from 'react-router';
import { useServices } from '@/app/contexts';
import { notificationStore, useNotifications, type AppNotification } from '@/app/notifications';
import { DemoBadge } from '@/components/ui/Badge';
import { Button } from '@/components/ui/Button';
import { Popover } from '@/components/ui/Popover';
import { cn } from '@/lib/cn';
import { formatRelative } from '@/lib/format';

const KIND_ICON = { price_alert: BellRing, opportunity: Sparkles, signal: Radar, system: Info } as const;

function Item({ n, onOpen }: { n: AppNotification; onOpen: () => void }) {
  const Icon = KIND_ICON[n.kind];
  const content = (
    <>
      <Icon aria-hidden className={cn('mt-0.5 size-4 shrink-0', n.kind === 'opportunity' ? 'text-forecast' : 'text-fg-2')} />
      <span className="min-w-0 flex-1">
        <span className={cn('block text-sm', n.read ? 'text-fg-2' : 'font-medium text-fg')}>{n.title}</span>
        <span className="block text-xs text-fg-3">{n.body}</span>
        <span className="mt-0.5 flex items-center gap-2 text-xs text-fg-3">
          {formatRelative(n.createdAt)}
          {n.provenance === 'demo' && <span className="text-demo">Simulated</span>}
        </span>
      </span>
      {!n.read && <span aria-label="Unread" className="mt-1.5 size-2 shrink-0 rounded-full bg-accent" />}
    </>
  );
  const cls = 'flex w-full items-start gap-2.5 rounded-md px-2.5 py-2 text-left hover:bg-hover';
  return n.href ? (
    <Link
      to={n.href}
      className={cls}
      onClick={() => {
        notificationStore.markRead(n.id);
        onOpen();
      }}
    >
      {content}
    </Link>
  ) : (
    <button type="button" className={cls} onClick={() => notificationStore.markRead(n.id)}>
      {content}
    </button>
  );
}

/** Notification centre (bell). Lists alert triggers and system notices. */
export function NotificationCenter() {
  const { items, unread } = useNotifications();
  const { source } = useServices();

  return (
    <Popover
      label="Notifications"
      align="end"
      className="w-[min(380px,calc(100vw-1.5rem))]"
      padded={false}
      trigger={(t) => (
        <button
          type="button"
          {...t}
          aria-label={unread ? `Notifications, ${unread} unread` : 'Notifications'}
          className="relative inline-flex size-9 items-center justify-center rounded-md text-fg-2 hover:bg-hover hover:text-fg"
        >
          <Bell aria-hidden className="size-4" />
          {unread > 0 && (
            <span aria-hidden className="num absolute top-1 right-1 flex h-4 min-w-4 items-center justify-center rounded-full bg-accent px-1 text-xs leading-none text-accent-fg">
              {unread > 9 ? '9+' : unread}
            </span>
          )}
        </button>
      )}
    >
      {(close) => (
        <div>
          <div className="flex items-center gap-2 border-b border-line px-3 py-2.5">
            <h2 className="text-sm font-semibold text-fg">Notifications</h2>
            {source === 'demo' && <DemoBadge label="Demo" detail="Generated by the in-browser alert monitor from simulated prices." />}
            <div className="ml-auto flex gap-1">
              <Button size="sm" variant="ghost" icon={CheckCheck} disabled={unread === 0} onClick={notificationStore.markAllRead}>
                Mark read
              </Button>
              <Button size="sm" variant="ghost" icon={Trash2} disabled={items.length === 0} onClick={notificationStore.clear} aria-label="Clear all notifications" />
            </div>
          </div>
          {items.length === 0 ? (
            <div className="px-4 py-8 text-center">
              <p className="text-sm font-medium text-fg">No notifications</p>
              <p className="mt-1 text-xs text-fg-3">
                {source === 'demo'
                  ? 'Create a price alert near the current price — it will fire here when the simulated price crosses it.'
                  : 'Alerts delivered by the notification service will appear here.'}
              </p>
              <Link to="/alerts" onClick={close} className="mt-3 inline-block text-sm text-accent underline-offset-2 hover:underline">
                Manage alerts
              </Link>
            </div>
          ) : (
            <ul className="max-h-96 overflow-y-auto p-1.5">
              {items.map((n) => (
                <li key={n.id}>
                  <Item n={n} onOpen={close} />
                </li>
              ))}
            </ul>
          )}
        </div>
      )}
    </Popover>
  );
}
