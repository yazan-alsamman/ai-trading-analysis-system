"""Encryption of feed tokens at rest (B1, docs/ctrader-feed.md#tokens).

Fernet (AES-128-CBC + HMAC-SHA256, from ``cryptography``, already installed through
``pyjwt[crypto]``) with a key derived from ``JWT_SECRET`` by HKDF-SHA256 with a purpose label.

Why ``JWT_SECRET`` and not a new ``FEED_ENCRYPTION_KEY``: it already exists on the server, is
random (64 characters, generated by the deploy), is required (the app refuses to start in
production without a strong one) and never leaves the server; a new key would be one more secret
to generate, back up and keep in sync between the API, the workers and the feed. HKDF with its
own label makes the derived key independent of the JWT signing key. The cost: rotating
``JWT_SECRET`` makes the stored tokens unreadable, and the account must be linked again (the
feed says so in its status and logs); docs/ctrader-feed.md documents it.
"""

from __future__ import annotations

import base64
from functools import lru_cache

from cryptography.fernet import Fernet, InvalidToken
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

from app.core.config import get_settings

PREFIX = "v1:"
_LABEL = b"trading/feed-credentials/fernet/v1"


class CredentialDecryptError(Exception):
    """A stored token cannot be decrypted (JWT_SECRET changed): link the account again."""


@lru_cache(maxsize=4)
def _fernet(secret: str) -> Fernet:
    key = HKDF(algorithm=hashes.SHA256(), length=32, salt=None, info=_LABEL).derive(secret.encode())
    return Fernet(base64.urlsafe_b64encode(key))


def encrypt(value: str) -> str:
    return PREFIX + _fernet(get_settings().jwt_secret).encrypt(value.encode()).decode()


def decrypt(value: str) -> str:
    if not value.startswith(PREFIX):
        raise CredentialDecryptError("unknown format")
    try:
        return _fernet(get_settings().jwt_secret).decrypt(value[len(PREFIX) :].encode()).decode()
    except InvalidToken:
        raise CredentialDecryptError("cannot decrypt (JWT_SECRET changed?)") from None
