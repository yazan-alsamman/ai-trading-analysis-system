"""Robustness checks on the Phase 3 walk-forward result (run after it; changes no result).

    python -m app.ml.robustness     # docs/phase3/robustness.{md,json}

1. Time dependence: trades that overlap in time or cluster in the same weeks are not independent,
   so the per-trade bootstrap CI may be too narrow. The rules' mean net R and the models' Brier
   skill and EV-filter difference are re-estimated with a cluster bootstrap that resamples whole
   calendar weeks or months.
2. Leakage: for every test window, every training row closed at least the embargo before the
   window opened, and the EV decision uses only quantities fixed at the CHoCH close.
3. Costs: the dataset's net R is realized R minus the round-trip cost of ``CostParams`` defaults."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from app.ml.dataset import DATASET, OUT_DIR
from app.ml.walkforward import EMBARGO, MODELS, closed_before, expected_value, windows

PREDICTIONS = DATASET.with_name("phase3_walkforward_predictions.parquet")
N_BOOT = 10_000


def overlap_share(df: pd.DataFrame) -> float:
    """Share of trades whose decision-to-exit span overlaps another trade's."""
    d, e = df["decision_ts"].to_numpy(), df["exit_ts"].to_numpy()
    order = np.argsort(d)
    d, e = d[order], e[order]
    overlaps = np.zeros(len(d), dtype=bool)
    latest_exit = e[0]
    for i in range(1, len(d)):
        if d[i] < latest_exit:
            overlaps[i] = True
            overlaps[np.flatnonzero(e[:i] > d[i])] = True
        latest_exit = max(latest_exit, e[i])
    return float(overlaps.mean())


def cluster_boot(pred: pd.DataFrame, key: pd.Series, stat, seed: int = 0) -> list[float]:
    """95% CI of ``stat(rows)`` when whole clusters (weeks or months) are resampled."""
    rng = np.random.default_rng(seed)
    groups = [g.index.to_numpy() for _, g in pred.groupby(key)]
    vals = []
    for _ in range(N_BOOT):
        pick = rng.integers(0, len(groups), len(groups))
        v = stat(pred.loc[np.concatenate([groups[k] for k in pick])])
        if np.isfinite(v):
            vals.append(v)
    return [float(np.quantile(vals, 0.025)), float(np.quantile(vals, 0.975))]


def _mean_net(rows: pd.DataFrame) -> float:
    return float(rows["net_r"].mean())


def _skill(name: str):
    def f(rows):
        y = rows["y"].to_numpy(float)
        se = (rows[f"p_{name}"].to_numpy() - y) ** 2
        se_base = (rows["p_base_rate"].to_numpy() - y) ** 2
        return 1 - se.mean() / se_base.mean()

    return f


def _difference(name: str):
    def f(rows):
        take = expected_value(rows[f"p_{name}"], rows["r_multiple"], rows["cost_r"]) > 0
        return rows.loc[take, "net_r"].mean() - rows["net_r"].mean() if take.any() else np.nan

    return f


def leakage_check(df: pd.DataFrame) -> dict:
    out = {}
    for start, _ in windows():
        train = closed_before(df, start)
        out[f"{start:%Y-%m}"] = {
            "training_rows": len(train),
            "latest_exit_plus_embargo_before_start": bool(
                (train["exit_ts"] + EMBARGO <= start).all()
            ),
        }
    return out


def run_checks(df: pd.DataFrame, pred: pd.DataFrame) -> dict:
    pred = pred.reset_index(drop=True)
    ts = pred["decision_ts"]
    keys = {
        "week": ts.dt.tz_convert(None).dt.to_period("W").astype(str),
        "month": ts.dt.tz_convert(None).dt.to_period("M").astype(str),
    }
    res = {
        "setups": len(pred),
        "overlap_share": overlap_share(pred),
        "clusters": {k: int(v.nunique()) for k, v in keys.items()},
        "rules_mean_net_r": _mean_net(pred),
        "rules_mean_net_r_ci95": {k: cluster_boot(pred, v, _mean_net) for k, v in keys.items()},
        "models": {
            name: {
                "brier_skill_ci95": {
                    k: cluster_boot(pred, v, _skill(name)) for k, v in keys.items()
                },
                "difference_ci95": {
                    k: cluster_boot(pred, v, _difference(name)) for k, v in keys.items()
                },
            }
            for name in MODELS
        },
        "leakage": leakage_check(df),
        "costs_consistent": bool(np.allclose(df["net_r"], df["realized_r"] - df["cost_r"])),
    }
    return res


def render(res: dict) -> str:
    def ci(x):
        return f"{x[0]:.3f} to {x[1]:.3f}"

    r = res["rules_mean_net_r_ci95"]
    lines = [
        "# Phase 3 — robustness of the walk-forward result",
        "",
        "_Generated by `python -m app.ml.robustness` after the single walk-forward run. It "
        "changes no result; it tests whether the conclusions hold under weaker assumptions._",
        "",
        "## Time dependence",
        "",
        f"- {res['overlap_share']:.1%} of the {res['setups']} out-of-sample trades overlap another "
        "trade in time.",
        f"- Clusters: {res['clusters']['week']} weeks, {res['clusters']['month']} months.",
        "",
        "| Quantity | Estimate | 95% CI, weeks resampled | 95% CI, months resampled |",
        "| --- | --- | --- | --- |",
        f"| Rules, mean net R | {res['rules_mean_net_r']:.3f} | {ci(r['week'])} | "
        f"{ci(r['month'])} |",
    ]
    for name, m in res["models"].items():
        b, d = m["brier_skill_ci95"], m["difference_ci95"]
        lines.append(f"| {name}, Brier skill | | {ci(b['week'])} | {ci(b['month'])} |")
        lines.append(
            f"| {name}, EV filter minus rules (net R) | | {ci(d['week'])} | {ci(d['month'])} |"
        )
    ok = all(v["latest_exit_plus_embargo_before_start"] for v in res["leakage"].values())
    lines += [
        "",
        "## Leakage",
        "",
        f"- Every training row closed at least a day before its test window opened: "
        f"**{'yes' if ok else 'NO'}** ({len(res['leakage'])} windows).",
        "- The EV decision uses the model's probability, the planned R and the round-trip cost in "
        "R. All three are fixed at the CHoCH close, before the fill and the outcome.",
        "",
        "## Costs",
        "",
        f"- Net R equals realized R minus the round-trip cost for every row: "
        f"**{'yes' if res['costs_consistent'] else 'NO'}**. The cost definition is `CostParams` "
        "defaults throughout (spread plus the larger of 50% or $0.10; $0.10 slippage on stops, "
        "inside realized R). The 2× stress doubles the round-trip cost, not the stop slippage.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    args = ap.parse_args(argv)
    res = run_checks(pd.read_parquet(DATASET), pd.read_parquet(PREDICTIONS))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "robustness.json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")
    (args.out / "robustness.md").write_text(render(res), encoding="utf-8")
    print(f"wrote {args.out / 'robustness.md'}")


if __name__ == "__main__":
    main()
