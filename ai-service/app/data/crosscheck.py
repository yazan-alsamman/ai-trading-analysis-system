"""FxPro vs Dukascopy cross-check on the fixed sample (P1 task 5).

    python -m app dukascopy compare     # docs/data_quality/dukascopy.{md,json}

Both feeds are bid M1 bars in UTC. For each instrument and year of the sample:

* ``corr``: correlation of 5-minute log returns (last close of each 5-minute bucket, buckets
  present in both feeds and consecutive);
* ``best_lag_min``: the shift of the Dukascopy series, from -90 to +90 minutes in 5-minute steps,
  with the highest correlation. Anything but 0 means one feed's clock is off;
* ``price_gap_x_range``: the median absolute difference of the 5-minute closes, as a multiple of
  the median FxPro 5-minute range (different brokers quote slightly different prices);
* coverage: buckets present in each feed and in both.

The gate was fixed with the sample, before any data was compared: in every year ``corr`` >= 0.9
and ``best_lag_min`` = 0. The two FxPro holes in ``EXTRA_DAYS`` are reported as bars per hour in
both feeds, so a hole can be told from a broker outage."""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from app.data import dukascopy as dk

OUT_DIR = Path(__file__).resolve().parents[2] / "docs" / "data_quality"
BUCKET = pd.Timedelta(minutes=5)
LAGS = range(-18, 19)  # in 5-minute buckets
MIN_CORR = 0.9


def closes(bars: pd.DataFrame) -> pd.DataFrame:
    """Last close and range of each 5-minute bucket."""
    b = bars.assign(bucket=bars["ts_utc"].dt.floor(BUCKET))
    g = b.groupby("bucket")
    return pd.DataFrame(
        {"close": g["close"].last(), "range": g["high"].max() - g["low"].min()}
    ).rename_axis("bucket")


def _returns(c: pd.Series) -> pd.Series:
    full = c.asfreq(BUCKET)
    return np.log(full).diff()


def compare_frames(fx: pd.DataFrame, duka: pd.DataFrame) -> dict:
    """The metrics above for one span of both feeds."""
    a, b = closes(fx), closes(duka)
    both = a.join(b, how="inner", lsuffix="_fx", rsuffix="_dk")
    out = {"buckets_fx": len(a), "buckets_dk": len(b), "buckets_both": len(both)}
    if len(both) < 50:
        return out
    ra = _returns(both["close_fx"])
    rb = _returns(both["close_dk"])
    corr = {k * 5: float(ra.corr(rb.shift(-k))) for k in LAGS}
    best = max(corr, key=lambda k: (corr[k], -abs(k)))
    gap = (both["close_fx"] - both["close_dk"]).abs().median()
    return out | {
        "corr": round(corr[0], 4),
        "best_lag_min": int(best),
        "best_lag_corr": round(corr[best], 4),
        "price_gap_x_range": round(float(gap / a["range"].median()), 3),
    }


def _hours(bars: pd.DataFrame, day: date) -> dict[str, int]:
    lo = pd.Timestamp(day, tz="UTC")
    on = bars[(bars["ts_utc"] >= lo) & (bars["ts_utc"] < lo + pd.Timedelta(days=1))]
    return {f"{h:02d}": int(n) for h, n in on["ts_utc"].dt.hour.value_counts().sort_index().items()}


def build(symbol: str, store: Path, cache: Path) -> dict:
    days = dk.sample_days(dk.store_first_year(symbol, store))
    duka = dk.load(symbol, days, cache)
    fx = pd.read_parquet(store / symbol / "m1.parquet", columns=["ts_utc", "high", "low", "close"])
    day = fx["ts_utc"].dt.tz_convert("UTC").dt.date
    fx = fx[day.isin(set(days)).to_numpy()]
    years = {}
    for y in sorted({d.year for d in days if d not in dk.EXTRA_DAYS}):
        years[str(y)] = compare_frames(
            fx[fx["ts_utc"].dt.year == y], duka[duka["ts_utc"].dt.year == y]
        )
    passed = all(
        v.get("corr", 0) >= MIN_CORR and v.get("best_lag_min") == 0 for v in years.values()
    )
    return {
        "symbol": symbol,
        "days_in_sample": len(days),
        "days_downloaded": int(sum(dk.path(symbol, d, cache).exists() for d in days)),
        "gate": {"min_corr": MIN_CORR, "best_lag_min": 0, "passed": passed},
        "by_year": years,
        "extra_days": {
            d.isoformat(): {
                "fxpro_bars_per_hour": _hours(fx, d),
                "dukascopy_bars_per_hour": _hours(duka, d),
            }
            for d in dk.EXTRA_DAYS
            if d.year >= dk.store_first_year(symbol, store)
        },
    }


def render(results: list[dict]) -> str:
    lines = [
        "# FxPro vs Dukascopy cross-check",
        "",
        "_Generated by `python -m app dukascopy compare`; the method and the gate are in"
        " `app/data/crosscheck.py`. Bid M1, UTC, sample fixed in `app/data/dukascopy.py`._",
        "",
        "| Instrument | Days | Gate (corr ≥ 0.9 and lag 0 every year) |",
        "| --- | --- | --- |",
        *[
            f"| {r['symbol']} | {r['days_downloaded']} of {r['days_in_sample']} |"
            f" {'pass' if r['gate']['passed'] else 'FAIL'} |"
            for r in results
        ],
    ]
    for r in results:
        lines += [
            "",
            f"## {r['symbol']}",
            "",
            "| Year | Buckets both | corr | best lag (min) | corr at best lag"
            " | price gap (× 5m range) |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for y, v in r["by_year"].items():
            cells = [v.get(k, "n/a") for k in ("corr", "best_lag_min", "best_lag_corr")]
            cells.append(v.get("price_gap_x_range", "n/a"))
            lines.append(f"| {y} | {v['buckets_both']:,} | " + " | ".join(map(str, cells)) + " |")
    return "\n".join(lines) + "\n"


def main(symbols: list[str], store: Path, cache: Path, out: Path = OUT_DIR) -> int:
    results = [build(s, store, cache) for s in symbols]
    out.mkdir(parents=True, exist_ok=True)
    (out / "dukascopy.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    (out / "dukascopy.md").write_text(render(results), encoding="utf-8", newline="\n")
    for r in results:
        days = f"{r['days_downloaded']}/{r['days_in_sample']}"
        print(f"{r['symbol']}: {days} days, gate {r['gate']['passed']}")
    return 0
