"""Sample counts for the P3 strictness decision: how many labelled setups a rule set yields.

    python -m app setups count --rules V5-S                 # every instrument in the store
    python -m app setups count --rules v1 --symbol XAUUSD

Counts only. The design allows counting setups on all history before the lockbox (2012-01-01 to
2026-01-09) to decide strict versus loosened rules; it does not allow looking at how they
performed there. So this module reports, per instrument and year, how many patterns, armed
setups and labelled (``CLOSED``) setups there are, and nothing else: no R, no hit rate, no
outcome. Performance is measured on the development period only (``python -m app setups label``).

Writes ``docs/phase3/counts_<rules>.md``."""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from app.config import Strategy, instruments, splits, strategy
from app.data.importer import DEFAULT_OUT as STORE
from app.data.sessions import is_open
from app.setups.builder import OUT_DIR
from app.setups.labels import label_all
from app.smc.detector import load_frames

GATE = 1000
START = pd.Timestamp("2012-01-01", tz="UTC")  # XAUUSD before 2011-08 is on a shifted clock


def history_frames(
    symbol: str, p: Strategy, store: Path = STORE, end: pd.Timestamp | None = None
) -> dict[str, pd.DataFrame]:
    """All bars from 2012 that closed by ``end`` (default: the lockbox start; the store holds
    nothing later)."""
    end = pd.Timestamp(splits().lockbox_start, tz="UTC") if end is None else end
    frames = {
        k: v[v["ts_utc"] >= START].reset_index(drop=True)
        for k, v in load_frames(symbol, end, store).items()
    }
    if p.break_is_gap:
        e = frames[p.entry_timeframe]
        frames[p.entry_timeframe] = e[is_open(e["ts_utc"], instruments()[symbol])].reset_index(
            drop=True
        )
    return frames


def count(symbol: str, p: Strategy, store: Path = STORE) -> pd.DataFrame:
    """Patterns, armed and labelled setups per year; the outcome columns are dropped unread."""
    df = label_all(history_frames(symbol, p, store), symbol, p)
    if df.empty:
        return pd.DataFrame(columns=["symbol", "year", "patterns", "armed", "labelled"])
    df = df[["year", "state"]]
    g = df.groupby("year")
    out = pd.DataFrame(
        {
            "patterns": g.size(),
            "armed": g["state"].apply(lambda s: int((s != "REJECTED").sum())),
            "labelled": g["state"].apply(lambda s: int((s == "CLOSED").sum())),
        }
    ).reset_index()
    out.insert(0, "symbol", symbol)
    return out


def render(p: Strategy, counts: pd.DataFrame) -> str:
    lab = (
        counts.pivot_table(index="year", columns="symbol", values="labelled", aggfunc="sum")
        .fillna(0)
        .astype(int)
    )
    lab["all"] = lab.sum(axis=1)
    totals = counts.groupby("symbol")[["patterns", "armed", "labelled"]].sum()
    lines = [
        f"# P3: sample counts, {p.rule_set}",
        "",
        "_Generated by `python -m app setups count`. Counts only, 2012-01-01 to 2026-01-09 (no"
        " performance outside the development period). Labelled = filled and closed by TP, SL or"
        " the horizon._",
        "",
        f"Labelled setups, all instruments: **{int(totals['labelled'].sum())}** (P3 gate: {GATE}).",
        "",
        "| Instrument | Patterns | Armed | Labelled |",
        "| --- | --- | --- | --- |",
        *[f"| {s} | {r.patterns} | {r.armed} | {r.labelled} |" for s, r in totals.iterrows()],
        "",
        "Labelled setups per year:",
        "",
        "| Year | " + " | ".join(lab.columns) + " |",
        "|" + " --- |" * (len(lab.columns) + 1),
        *[f"| {y} | " + " | ".join(str(v) for v in r) + " |" for y, r in lab.iterrows()],
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="python -m app setups count")
    ap.add_argument("--rules", default="V5-S")
    ap.add_argument("--symbol", action="append")
    ap.add_argument("--store", type=Path, default=STORE)
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    args = ap.parse_args(argv)
    p = strategy(args.rules)
    symbols = args.symbol or sorted(
        x.parent.name for x in args.store.glob("*/import.json") if x.parent.name in instruments()
    )
    counts = pd.concat([count(s, p, args.store) for s in symbols], ignore_index=True)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / f"counts_{p.rule_set}.md").write_text(
        render(p, counts), encoding="utf-8", newline="\n"
    )
    print(
        p.rule_set,
        counts.groupby("symbol")["labelled"].sum().to_dict(),
        "total",
        int(counts["labelled"].sum()),
    )
    return 0
