"""``python -m app research post-counts``: the post-approval counts of
docs/strategies/PREREG.md, section 12, written to ``docs/strategies/counts_post.md`` and
``counts_post_by_year.csv``. The computation is ``app.management.counts`` (unchanged since the
rules were frozen); this module only runs it after approval, on the frozen rules, with delta*_S
from the pre-approval counts, and writes the report. Exits stay inside the computation."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from app.config import instruments
from app.data.importer import DEFAULT_OUT as STORE
from app.management.counts import run
from app.research.strategy_eval import COUNTS, deltas, registered
from app.strategies.cli import OUT_DIR


def render(tables: dict[str, pd.DataFrame], commit: str, head: str, run_date: str) -> str:
    p = tables["power"]
    cols = ["strategy", "family", "n", "K", "sigma", "DE", "mde_alpha_m", "mde_alpha", "delta_star",
            "n_unval"]  # fmt: skip
    y = tables["by_year"]
    sums = y.drop(columns=["symbol", "year"]).groupby("strategy").sum().reset_index()

    def table(df: pd.DataFrame, cs: list[str]) -> list[str]:
        cell = lambda v: f"{v:.3f}" if isinstance(v, float) else str(v)  # noqa: E731
        return [
            "| " + " | ".join(cs) + " |",
            "|" + " --- |" * len(cs),
            *["| " + " | ".join(cell(v) for v in r) + " |" for r in df[cs].itertuples(index=False)],
        ]

    return "\n".join(
        [
            "# Stage B: post-approval counts (primary period)",
            "",
            f"_Generated by `python -m app research post-counts` on {run_date}. Rules frozen at"
            f" `{commit}`, code `{head}`. Bars loaded only to 2024-07-01. Exits are used inside the"
            " computation only; no R, exit reason, exit price or exit time is written. Descriptive"
            " only (`PREREG.md` sections 8 and 12): the power statements inform the reader and"
            " decide nothing._",
            "",
            "## Family A trades and served signals, 2018-01 to 2024-06",
            "",
            *table(sums, [c for c in sums.columns if c != "family"]),
            "",
            "## Power statements (section 8)",
            "",
            *table(p, cols),
            "",
            "Per instrument and year: `counts_post_by_year.csv`.",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m app research post-counts")
    ap.add_argument("--symbol", action="append")
    ap.add_argument("--store", type=Path, default=STORE)
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    args = ap.parse_args(argv)
    try:
        commit, head, _ = registered()
        d = deltas(COUNTS, commit)
    except (PermissionError, ValueError) as e:
        print(f"refused: {e}", file=sys.stderr)
        return 2
    symbols = args.symbol or sorted(s for s in instruments() if (args.store / s).is_dir())
    tables = run(symbols, args.store, d)
    args.out.mkdir(parents=True, exist_ok=True)
    run_date = pd.Timestamp.now(tz="UTC").date().isoformat()
    (args.out / "counts_post.md").write_text(
        render(tables, commit, head, run_date), encoding="utf-8", newline="\n"
    )
    tables["by_year"].to_csv(args.out / "counts_post_by_year.csv", index=False, lineterminator="\n")
    print(f"wrote {args.out / 'counts_post.md'}")
    return 0
